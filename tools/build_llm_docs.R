#!/usr/bin/env Rscript
# Markdown copies of the NNS book and help pages for readers that take plain text.
#
#   Rscript tools/build_llm_docs.R [--src DIR] [--out DIR] [--strict]
#
# Reads book/*.Rmd and man/*.Rd under --src (default ".") and writes --out
# (default "docs/llm"): one Markdown file per chapter and help page with the
# formulas kept as LaTeX in $...$ and $$...$$, plus index.md and check.md.
# index.md links the vignettes where pkgdown publishes them as Markdown.
# No R chunk is run, so there is no chunk output. Needs pandoc and jsonlite.
#
# Each output is read back with pandoc and its formulas and code blocks are
# compared with those pandoc reads from the source. A difference, or Rd markup
# without a conversion below, goes to check.md and is raised as a warning; it
# changes the exit status only with --strict. A pandoc failure stops the
# build. An Rd syntax problem only shows as an R warning.

# -smart keeps quotes, dashes and "..." as typed, so a sentence can be searched for
PANDOC_FROM <- "markdown-smart+autolink_bare_uris+tex_math_single_backslash"
PANDOC_TO <- "markdown-smart-raw_attribute-simple_tables-multiline_tables-grid_tables"
# where the site publishes the book's HTML and images, seen from OUT/chapters/<file>.md
SITE_ROOT <- "../../book/"
# \alias -> help page, filled by build() and used to resolve \link
RD_ALIAS <- list()
# help page sections in output order
RD_SECTIONS <- c("\\description" = "Description", "\\usage" = "Usage", "\\arguments" = "Arguments",
                 "\\format" = "Format", "\\details" = "Details", "\\value" = "Value", "\\note" = "Note",
                 "\\section" = "", "\\examples" = "Examples", "\\source" = "Source",
                 "\\references" = "References", "\\seealso" = "See also", "\\author" = "Author")
# top-level Rd entries that are not sections of the page
RD_META <- c("TEXT", "COMMENT", "\\name", "\\alias", "\\title", "\\keyword", "\\docType",
             "\\encoding", "\\concept")
# tags written as the text inside them; any other tag without a case in rd_md() is reported
RD_PLAIN <- c("LIST", "\\donttest", "\\file", "\\var", "\\samp", "\\env", "\\option", "\\command",
              "\\dfn", "\\cite", "\\acronym", "\\kbd", "\\verb", "\\special")
RD_SKIPPED <- character()

# ---------------------------------------------------------------- utilities

read_lines <- function(p) readLines(p, warn = FALSE, encoding = "UTF-8")
write_lines <- function(x, p) {
  # x may be read from p, which opening the connection truncates
  force(x)
  dir.create(dirname(p), recursive = TRUE, showWarnings = FALSE)
  con <- file(p, open = "wb")
  on.exit(close(con))
  writeLines(x, con, useBytes = TRUE)
}
sh <- function(cmd, args) {
  err <- tempfile()
  on.exit(unlink(err))
  out <- suppressWarnings(system2(cmd, args, stdout = TRUE, stderr = err))
  if (!is.null(attr(out, "status")))
    stop(cmd, " ", paste(args, collapse = " "), " failed:\n",
         paste(c(out, read_lines(err)), collapse = "\n"), call. = FALSE)
  out
}
pandoc <- function(lines, from, to, extra = character()) {
  tmp <- tempfile(fileext = ".md")
  res <- tempfile()
  on.exit(unlink(c(tmp, res)))
  write_lines(lines, tmp)
  # on reading, a pipe table with a line wider than --columns gets fixed
  # column widths and can then only be written as a multiline table
  sh("pandoc", c("-f", from, "-t", to, "--wrap=preserve", "--preserve-tabs",
                 if (to == "json") "--columns=100000", extra, "-o", shQuote(res), shQuote(tmp)))
  read_lines(res)
}
generated <- function(rel, edit)
  sprintf("<!-- Generated by tools/build_llm_docs.R from %s. Edit %s, not this file. -->", rel, edit)

# ------------------------------------------------------------ pandoc checks

# Formulas and code blocks as pandoc parses them, in document order.
ast_nodes <- function(json) {
  ast <- jsonlite::fromJSON(paste(json, collapse = "\n"), simplifyVector = FALSE)
  math <- code <- tex <- character()
  walk <- function(x, in_figure = FALSE) {
    if (!is.list(x)) return(invisible())
    t <- x[["t"]]
    if (is.character(t) && length(t) == 1) {
      if (t == "Math")
        math <<- c(math, paste(x$c[[1]]$t, x$c[[2]], sep = ": "))
      else if (t == "CodeBlock")
        code <<- c(code, x$c[[2]])
      else if (t %in% c("RawBlock", "RawInline") && x$c[[1]] %in% c("tex", "latex"))
        tex <<- c(tex, x$c[[2]])
      # a figure repeats its caption as the image alt text
      else if (t == "Image" && in_figure) return(invisible())
      else if (t == "Figure") in_figure <- TRUE
    }
    for (y in x) walk(y, in_figure)
  }
  walk(ast$blocks)
  list(math = math, code = code, tex = tex)
}

# One row of check.md: the source items against the output items, in order.
compare <- function(what, want, got) {
  n <- max(length(want), length(got))
  w <- want[seq_len(n)]
  g <- got[seq_len(n)]
  bad <- which(is.na(w) | is.na(g) | w != g)
  show <- function(s) if (is.na(s)) "(nothing)" else gsub("\\s+", " ", substr(s, 1, 80))
  list(what = what, n = length(want), differ = length(bad),
       msg = if (length(bad)) sprintf("%d of %d differ. First: %s %d is `%s` in the source and `%s` in the output.",
                                      length(bad), length(want), what, bad[1], show(w[bad[1]]), show(g[bad[1]])))
}

# ----------------------------------------------------------- Rmd -> Markdown

knitr_fences <- function(lines) {
  # ```{r label, opts}  ->  ```{.r chunk="label, opts"}, which pandoc keeps
  re <- "^(\\s*(`{3,}|~{3,}))\\s*\\{([A-Za-z]+)[ ,]*(.*)\\}\\s*$"
  hit <- grepl(re, lines)
  opts <- gsub('"', "'", sub(re, "\\4", lines[hit]))
  lines[hit] <- paste0(sub(re, "\\1{.\\3", lines[hit]),
                       ifelse(nzchar(opts), paste0(' chunk="', opts, '"'), ""), "}")
  lines
}

split_yaml <- function(lines) {
  end <- if (length(lines) && lines[1] == "---") which(lines[-1] %in% c("---", "..."))[1] + 1 else NA
  if (is.na(end)) return(list(title = NA_character_, body = lines))
  title <- grep("^title:", lines[seq_len(end)], value = TRUE)[1]
  list(title = gsub("^title:\\s*[\"']?|[\"']?\\s*$", "", title), body = lines[-seq_len(end)])
}

# Three things pandoc's Markdown writer would otherwise do differently:
# formulas go out as raw text because newer versions trim display math,
# a code block without a language gets one because it would be written as an
# indented block, and relative links and image paths point at the published site.
lua_filter <- function() {
  f <- tempfile(fileext = ".lua")
  write_lines(c("function Math(el)",
                "  local d = el.mathtype == 'DisplayMath' and '$$' or '$'",
                "  return pandoc.RawInline('markdown', d .. el.text .. d)",
                "end",
                "function CodeBlock(el)",
                "  if #el.classes == 0 then el.classes = {'text'} end",
                "  return el",
                "end",
                "local function at_site(url)",
                "  if url:match('^%a[%w+.-]*:') or url:match('^[/#]') then return url end",
                sprintf("  return '%s' .. url", SITE_ROOT),
                "end",
                "function Image(el) el.src = at_site(el.src) return el end",
                "function Link(el) el.target = at_site(el.target) return el end"), f)
  f
}

build_rmd <- function(file, rel, out_rel, out) {
  src <- split_yaml(read_lines(file))
  body <- knitr_fences(src$body)
  filter <- lua_filter()
  on.exit(unlink(filter))
  json <- pandoc(body, PANDOC_FROM, "json")
  md <- pandoc(json, "json", PANDOC_TO, c("--lua-filter", shQuote(filter)))
  h1 <- trimws(sub("\\s*\\{[^}]*\\}\\s*$", "", sub("^# ", "", grep("^# ", md, value = TRUE)[1])))
  write_lines(c(generated(rel, "the Rmd"), "",
                if (!is.na(src$title)) c(paste("#", src$title), ""), md),
              file.path(out, out_rel))
  want <- ast_nodes(json)
  got <- ast_nodes(pandoc(md, "markdown", "json"))
  list(rel = rel, out = out_rel, title = h1,
       checks = list(compare("formula", want$math, got$math),
                     compare("raw LaTeX block", want$tex, got$tex),
                     compare("code block", want$code, got$code)))
}

# ------------------------------------------------------------ Rd -> Markdown

rd_plain <- function(x) {
  if (is.character(x)) return(paste(x, collapse = ""))
  paste(vapply(x, rd_plain, ""), collapse = "")
}

rd_md <- function(x, ctx = "") {
  tag <- attr(x, "Rd_tag")
  kids <- function(c = ctx) paste(vapply(x, rd_md, "", ctx = c), collapse = "")
  if (is.null(tag)) return(if (is.character(x)) paste(x, collapse = "") else kids())
  switch(tag,
    # a bare $ in prose would read as the start of a formula
    TEXT = if (ctx == "code") paste(x, collapse = "") else
      gsub("$", "\\$", paste(x, collapse = ""), fixed = TRUE),
    RCODE = , VERB = paste(x, collapse = ""),
    COMMENT = , "\\dontshow" = "",
    USERMACRO = if (identical(attr(x, "macro"), "\\doi"))
      sprintf("[doi:%s](https://doi.org/%s)", x[2], x[2]) else "",
    "\\Sexpr" = if (grepl("Rd_expr_doi", rd_plain(x))) "" else
      paste0("`\\Sexpr{", rd_plain(x), "}`"),
    "\\code" = {
      inner <- kids("code")
      if (grepl("](", inner, fixed = TRUE)) inner
      else if (grepl("`", inner, fixed = TRUE)) paste0("`` ", inner, " ``")
      else paste0("`", inner, "`")
    },
    "\\link" = {
      txt <- rd_plain(x)
      opt <- attr(x, "Rd_option")
      # \link[pkg]{topic} points into another package
      page <- if (is.null(opt)) RD_ALIAS[[txt]] else
        if (startsWith(opt, "=")) RD_ALIAS[[substring(opt, 2)]]
      lab <- if (ctx == "code") paste0("`", txt, "`") else txt
      if (is.null(page)) txt else sprintf("[%s](%s.md)", lab, page)
    },
    "\\eqn" = paste0("$", trimws(rd_plain(x[[1]])), "$"),
    "\\deqn" = paste0("\n\n$$", rd_plain(x[[1]]), "$$\n\n"),
    "\\emph" = paste0("*", kids(), "*"),
    "\\strong" = , "\\bold" = , "\\pkg" = paste0("**", kids(), "**"),
    "\\url" = , "\\email" = paste0("<", rd_plain(x), ">"),
    "\\href" = sprintf("[%s](%s)", rd_md(x[[2]]), rd_plain(x[[1]])),
    "\\sQuote" = paste0("'", kids(), "'"),
    "\\dQuote" = paste0("\"", kids(), "\""),
    "\\ldots" = , "\\dots" = "...",
    "\\R" = "R",
    "\\cr" = "  \n",
    "\\tab" = " | ",
    "\\dontrun" = paste0("## Not run:", kids(), "## End(Not run)"),
    "\\method" = , "\\S3method" = paste0(rd_plain(x[[1]]), ".", rd_plain(x[[2]])),
    "\\itemize" = , "\\enumerate" = , "\\describe" = {
      body <- kids(if (tag == "\\enumerate") "enum" else "list")
      # a list inside a list item is indented under it
      paste0("\n", if (ctx %in% c("list", "enum")) gsub("\n(?=\\S)", "\n    ", body, perl = TRUE) else body, "\n")
    },
    "\\item" = {
      if (length(x) != 2) return(if (ctx == "enum") "\n1. " else "\n- ")
      name <- trimws(rd_md(x[[1]], "code"))
      if (ctx == "arguments" && !startsWith(name, "`")) name <- paste0("`", name, "`")
      sprintf("\n- %s: %s\n", name,
              gsub("\n(?=\\S)", "\n  ", trimws(rd_md(x[[2]], "")), perl = TRUE))
    },
    {
      if (!tag %in% RD_PLAIN) RD_SKIPPED <<- c(RD_SKIPPED, tag)
      kids()
    })
}

# First argument of every \eqn and \deqn, brace-matched in the raw Rd text.
rd_formulas <- function(raw) {
  txt <- paste(raw, collapse = "\n")
  m <- regmatches(txt, gregexpr("(?s)\\\\d?eqn(\\{(?:[^{}\\\\]|\\\\.|(?1))*\\})", txt, perl = TRUE))[[1]]
  body <- substr(m, regexpr("{", m, fixed = TRUE) + 1, nchar(m) - 1)
  display <- startsWith(m, "\\deqn")
  paste(ifelse(display, "DisplayMath:", "InlineMath:"), ifelse(display, body, trimws(body)))
}

build_rd <- function(file, rel, out_rel, out) {
  rd <- tools::parse_Rd(file, encoding = "UTF-8")
  raw <- read_lines(file)
  tags <- vapply(rd, function(e) attr(e, "Rd_tag"), "")
  sec <- function(t) rd[[match(t, tags)]]
  name <- trimws(rd_plain(sec("\\name")))
  title <- trimws(gsub("\\s+", " ", rd_plain(sec("\\title"))))
  roxygen <- sub("^% Please edit documentation in ", "",
                 grep("^% Please edit documentation in ", raw, value = TRUE)[1])
  o <- c(generated(rel, if (is.na(roxygen)) "the Rd" else paste("the roxygen block in", roxygen)),
         "", sprintf("# `%s`: %s", name, title), "")
  RD_SKIPPED <<- character()
  for (t in names(RD_SECTIONS)) for (e in rd[tags == t]) {
    part <- if (t == "\\section") e[[2]] else e
    ctx <- switch(t, "\\usage" = , "\\examples" = "code", "\\arguments" = "arguments", "")
    body <- paste(vapply(part, rd_md, "", ctx = ctx), collapse = "")
    body <- if (ctx == "code") c("```r", gsub("^\n+|\\s+$", "", body), "```") else
      gsub("\n{3,}", "\n\n", gsub("[ \t]+\n", "\n", trimws(body)))
    if (any(nzchar(body)))
      o <- c(o, paste("##", if (t == "\\section") trimws(rd_plain(e[[1]])) else RD_SECTIONS[[t]]), "", body, "")
  }
  o <- unlist(strsplit(paste(o, collapse = "\n"), "\n", fixed = TRUE))
  write_lines(o, file.path(out, out_rel))
  ticks <- function(t) paste0("`", unique(t), "`", collapse = ", ")
  left_out <- setdiff(tags, c(names(RD_SECTIONS), RD_META))
  skipped <- c(if (length(left_out)) paste("top-level entry left out:", ticks(left_out)),
               if (length(RD_SKIPPED)) paste("no conversion, written as the text inside:", ticks(RD_SKIPPED)))
  n <- length(unique(c(left_out, RD_SKIPPED)))
  list(rel = rel, out = out_rel, name = name, title = title, internal = "internal" %in%
         vapply(rd[tags == "\\keyword"], function(k) trimws(rd_plain(k)), ""),
       checks = c(list(compare("formula", rd_formulas(raw), ast_nodes(pandoc(o, "markdown", "json"))$math)),
                  if (n) list(list(what = "Rd markup not converted", n = n, differ = n,
                                   msg = paste0(paste(skipped, collapse = "; "), ".")))))
}

rd_aliases <- function(files) {
  map <- list()
  for (f in files) {
    a <- regmatches(l <- read_lines(f), regexec("^\\\\alias\\{(.*)\\}\\s*$", l))
    for (m in Filter(length, a)) map[[m[2]]] <- sub("\\.Rd$", "", basename(f))
  }
  map
}

# ------------------------------------------------------- index and reports

find_sources <- function(src) {
  ls <- function(dir, pattern) sort(list.files(file.path(src, dir), pattern), method = "radix")
  book <- c(ls("book", "^index\\.Rmd$"), ls("book", "^chapter-.*\\.Rmd$"))
  key <- sub("^chapter-([0-9]+)-.*", "ch\\1.md", sub("^index\\.Rmd$", "preface.md", book))
  man <- ls("man", "\\.Rd$")
  data.frame(kind = rep(c("chapters", "reference"), c(length(book), length(man))),
             rel = c(file.path("book", book), file.path("man", man)),
             out = c(file.path("chapters", key), file.path("reference", sub("Rd$", "md", man))))
}

write_index <- function(src, out, built) {
  desc <- read.dcf(file.path(src, "DESCRIPTION"), fields = c("Package", "Version"))
  vig <- sort(list.files(file.path(src, "vignettes"), "\\.Rmd$"), method = "radix")
  vig_title <- vapply(vig, function(v) split_yaml(read_lines(file.path(src, "vignettes", v)))$title, "")
  section <- function(heading, kind, label) {
    items <- unlist(lapply(Filter(function(b) dirname(b$out) == kind, built), label))
    if (length(items)) c(heading, "", items, "")
  }
  write_lines(c(
    sprintf("# %s %s documentation as Markdown", desc[1, "Package"], desc[1, "Version"]),
    "",
    "Generated from the package sources by `tools/build_llm_docs.R`. Formulas are LaTeX between `$...$` and `$$...$$`. Code is copied from the sources and is not run, so chunk output and generated figures are absent.",
    "",
    section("## Book", "chapters", function(b) sprintf("- [%s%s](%s)", if (grepl("/ch[0-9]+\\.md$", b$out))
      sub(".*/ch0*([0-9]+)\\.md$", "\\1. ", b$out) else "", b$title, b$out)),
    if (length(vig)) c(
      "## Vignettes", "",
      "pkgdown publishes the vignettes as Markdown with their chunk output. Formulas there are LaTeX between `` $`...`$ `` and in ```` ``` math ```` blocks.",
      "", sprintf("- [%s](../articles/%s)", vig_title, sub("Rmd$", "md", vig)), ""),
    section("## Function reference", "reference", function(b)
      sprintf("- [%s](%s): %s%s", b$name, b$out, b$title, if (b$internal) " (internal)" else "")),
    "## Build",
    "",
    "- [check.md](check.md): formulas and code blocks of every file compared with its source."),
    file.path(out, "index.md"))
}

write_check <- function(out, built, pandoc_version) {
  rows <- unlist(lapply(built, function(b) vapply(b$checks, function(c)
    sprintf("| %s | %s | %d | %d |", b$out, c$what, c$n, c$differ), "")))
  bad <- unlist(lapply(built, function(b) lapply(b$checks, function(c)
    if (c$differ) sprintf("- %s: %s", b$out, c$msg))))
  write_lines(c("# Source and output compared", "",
                sprintf("Each output file was read back with %s. Its formulas (display or inline, and the LaTeX body), raw LaTeX blocks and code blocks must equal those pandoc reads from the source, in order. A help page is checked for its `\\eqn` and `\\deqn` formulas, and Rd markup the script has no conversion for is listed.", pandoc_version),
                "", "| file | compared | in source | differ |", "|---|---|---|---|", rows, "",
                "## Differences", "", if (length(bad)) bad else "None."),
              file.path(out, "check.md"))
  bad
}

# ------------------------------------------------------------------- main

build <- function(src, out) {
  if (!nzchar(Sys.which("pandoc"))) stop("pandoc is not on the PATH", call. = FALSE)
  pandoc_version <- sh("pandoc", "--version")[1]
  s <- find_sources(src)
  rd <- s$kind == "reference"
  RD_ALIAS <<- rd_aliases(file.path(src, s$rel[rd]))
  built <- lapply(seq_len(nrow(s)), function(i)
    (if (rd[i]) build_rd else build_rmd)(file.path(src, s$rel[i]), s$rel[i], s$out[i], out))
  write_index(src, out, built)
  write_check(out, built, pandoc_version)
}

main <- function(args = commandArgs(trailingOnly = TRUE)) {
  opt <- function(name, default) {
    i <- match(paste0("--", name), args)
    if (is.na(i)) default else args[i + 1]
  }
  src <- normalizePath(opt("src", "."), mustWork = TRUE)
  out <- opt("out", file.path(src, "docs", "llm"))
  bad <- build(src, out)
  cat(sprintf("%s written, differences from the sources: %d\n", out, length(bad)))
  if (length(bad)) {
    # GitHub Actions turns ::warning:: lines into annotations on the run
    cat(sprintf("%s%s\n", if (nzchar(Sys.getenv("GITHUB_ACTIONS"))) "::warning::" else "Warning: ",
                sub("^- ", "", bad)), sep = "")
    if ("--strict" %in% args) quit(status = 1)
  }
}

